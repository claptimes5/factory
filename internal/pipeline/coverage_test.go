func TestParseCoverage(t *testing.T) {
	out := "ok  \tfixture/calc\t0.002s\tcoverage: 75.0% of statements\n" +
		"\tfixture/empty\t\tcoverage: 0.0% of statements\n" +
		"FAIL\tfixture/bad\t0.01s\n" +
		"?   \tfixture/none\t[no test files]\n" +
		"web/src/util 92.5%\n"
	got := parseCoverage(out)
	want := map[string]float64{"fixture/calc": 75, "fixture/empty": 0, "web/src/util": 92.5}
	if len(got) != len(want) {
		t.Fatalf("got %v", got)
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s = %v, want %v", k, got[k], v)
		}
	}
}

// Code added without tests lowers its package's coverage and fails the
// gate; the same code with a test passes.
func TestCoverageFloor(t *testing.T) {
	seed := map[string]string{
		"calc/calc.go":      "package calc\n\nfunc Double(x int) int { return 2 * x }\n",
		"calc/calc_test.go": "package calc\n\nimport \"testing\"\n\nfunc TestDouble(t *testing.T) {\n\tif Double(2) != 4 {\n\t\tt.Fatal()\n\t}\n}\n",
	}
	untested := func(work string) error {
		if err := writeFile(work, "calc/calc.go", "package calc\n\nfunc Double(x int) int { return 2 * x }\n\nfunc Half(x int) int {\n\tif x < 0 {\n\t\treturn -(-x / 2)\n\t}\n\treturn x / 2\n}\n"); err != nil {
			return err
		}
		return goodBuild(work)
	}
	tested := func(work string) error {
		if err := untested(work); err != nil {
			return err
		}
		writeFile(work, "calc/half_test.go", "package calc\n\nimport \"testing\"\n\nfunc TestHalf(t *testing.T) {\n\tif Half(4) != 2 || Half(-4) != -2 {\n\t\tt.Fatal()\n\t}\n}\n")
		return commitIn(work, "test Half")
	}
	ctx := context.Background()
	for _, c := range []struct {
		name  string
		build func(string) error
		fail  bool
	}{{"untested", untested, true}, {"tested", tested, false}} {
		t.Run(c.name, func(t *testing.T) {
			e := setupWith(t, seed)
			e.p.Cfg.Gates.Coverage = "go test -count=1 -cover {pkgs}"
			e.addIssue(1)
			e.claude.builds = []func(string) error{c.build}
			e.codex.reviews = []string{pass}
			e.p.Drain(ctx)
			jobs, _ := e.p.Store.ListJobs(ctx, store.JobFilter{ItemID: e.item(t, 1).ID, Kind: "implement"})
			if len(jobs) == 0 {
				t.Fatal("no implement job")
			}
			last := jobs[len(jobs)-1]
			if got := strings.Contains(last.Error, "coverage=fail"); got != c.fail {
				t.Fatalf("coverage failed = %v, want %v; error: %s", got, c.fail, last.Error)
			}
			if c.fail && !strings.Contains(last.Error, "calc: 100.0% → 25.0%") {
				t.Fatalf("error doesn't say what fell: %s", last.Error)
			}
		})
	}
}

func TestCoverable(t *testing.T) {
	root := t.TempDir()
	for name, body := range map[string]string{
		"a/a.go":            "package a\n",
		"a/a.pb.go":         "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage a\n",
		"vendor/x/y/y.go":   "package y\n",
		"tools/sub/go.mod":  "module sub\n",
		"tools/sub/in/i.go": "package in\n",
		"tools/tools.go":    "//go:build tools\n\npackage tools\n",
		"cmd/x/main.go":     "package main\n\nfunc main() {}\n",
	} {
		if err := writeFile(root, name, body); err != nil {
			t.Fatal(err)
		}
	}
	for f, want := range map[string]bool{
		"a/a.go": true, "a/a.pb.go": false, "vendor/x/y/y.go": false,
		"tools/sub/in/i.go": false, "gone/g.go": true, "tools/tools.go": false,
	} {
		if got := coverable(root, f); got != want {
			t.Errorf("coverable(%s) = %v, want %v", f, got, want)
		}
	}
	if !isMain(root, "cmd/x") || isMain(root, "a") {
		t.Error("isMain")
	}
}

// Packages compare by directory: a renamed module still has its floor.
func TestByDir(t *testing.T) {
	dirs := map[string]bool{".": true, "calc": true}
	got := byDir(map[string]float64{"renamed": 50, "renamed/calc": 80, "renamed/other": 10}, "renamed", dirs)
	if len(got) != 2 || got["."] != 50 || got["calc"] != 80 {
		t.Fatalf("byDir = %v", got)
	}
}

// Untested code in a new package doesn't escape the floor.
func TestCoverageNewPackageNeedsTests(t *testing.T) {
	seed := map[string]string{
		"calc/calc.go":      "package calc\n\nfunc Double(x int) int { return 2 * x }\n",
		"calc/calc_test.go": "package calc\n\nimport \"testing\"\n\nfunc TestDouble(t *testing.T) {\n\tif Double(2) != 4 {\n\t\tt.Fatal()\n\t}\n}\n",
	}
	build := func(work string) error {
		if err := writeFile(work, "half/half.go", "package half\n\nfunc Half(x int) int { return x / 2 }\n"); err != nil {
			return err
		}
		return goodBuild(work)
	}
	ctx := context.Background()
	e := setupWith(t, seed)
	e.p.Cfg.Gates.Coverage = "go test -count=1 -cover {pkgs}"
	e.addIssue(1)
	e.claude.builds = []func(string) error{build}
	e.codex.reviews = []string{pass}
	e.p.Drain(ctx)
	jobs, _ := e.p.Store.ListJobs(ctx, store.JobFilter{ItemID: e.item(t, 1).ID, Kind: "implement"})
	if len(jobs) == 0 {
		t.Fatal("no implement job")
	}
	if last := jobs[len(jobs)-1]; !strings.Contains(last.Error, "half: new, with no tests") {
		t.Fatalf("error: %s", last.Error)
	}
}
